def build_excuse_prompt(
    item_name: str,
    amount: int,
    category: str,
    remaining: int,
    reward_budget: int,
) -> str:
    """支出の「言い訳」生成プロンプトを構築する。

    Args:
        item_name:     商品名
        amount:        金額
        category:      ARS カテゴリ名
        remaining:     今月の残り予算
        reward_budget: 今月の総ご褒美予算

    Returns:
        Bedrock invoke_text に渡す文字列
    """
    # 予算余裕の判定
    if reward_budget > 0:
        ratio = remaining / reward_budget
    else:
        ratio = 0.0

    if ratio > 0.5:
        budget_hint = "予算はまだ余裕あり"
    elif ratio > 0.2:
        budget_hint = "予算は少し使ってきた"
    else:
        budget_hint = "予算がやや厳しくなってきた"

    # SEC-3-02: 入力長ガード
    safe_name = (item_name or "お買い物")[:100]
    safe_cat = category[:50]

    return (
        f"<expense_info>\n"
        f"商品名: {safe_name}\n"
        f"金額: {amount:,}円\n"
        f"ARS カテゴリ: {safe_cat}\n"
        f"予算状況: {budget_hint}（残り {remaining:,}円）\n"
        f"</expense_info>\n\n"
        f"この支出を「{safe_cat}」として正当化する言い訳を 1〜2 文で生成してください。"
        f"予算状況に応じて適切なトーンで。"
    )


def build_clarification_prompt(answer_text: str, partial_items: list[dict]) -> str:
    """追加質問への回答から支出情報を補完するプロンプトを生成する"""
    safe_text = answer_text[:1000]
    partial_info = ""
    if partial_items:
        item = partial_items[0]
        if item.get("item_name"):
            partial_info = f"（商品名: {item['item_name']}）"
    return f"""ユーザーが支出の金額を答えました。金額を抽出して JSON のみを返してください。

{partial_info}
ユーザーの回答: {safe_text}

出力形式（JSON のみ）:
{_OUTPUT_FORMAT}

注意: 金額が読み取れない場合は amount を null にしてください。is_expense は常に true にしてください。"""
